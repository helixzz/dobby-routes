SUPPORTED_FORMATS = ("bird", "routeros", "nftables", "singbox")


def write_bgp_routes(
    filepath: str,
    cidrs: list[str],
    timestamp: Optional[str] = None,
    ip_version: int = 4,
    inverse: bool = False,
) -> None:
    ts = _resolve_timestamp(timestamp)
    family = "IPv6" if ip_version == 6 else "IPv4"
    direction = "Inverse" if inverse else "China mainland"
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(f"# {direction} {family} BGP-active minimized route table\n")
        f.write(f"# Generated by dobby-routes on {ts} UTC\n")
        f.write(f"# Total routes: {len(cidrs)}\n")
        f.write("#\n")
        for cidr in cidrs:
            f.write(f"{cidr}\n")


def write_bird_prefix_set(
    filepath: str,
    symbol: str,
    cidrs: list[str],
    timestamp: Optional[str] = None,
) -> None:
    ts = _resolve_timestamp(timestamp)
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(f"# BIRD2 prefix set: {symbol}\n")
        f.write(f"# Generated by dobby-routes on {ts} UTC\n")
        f.write(f"# Total routes: {len(cidrs)}\n")
        if not cidrs:
            f.write(f"# Empty prefix set ({symbol})\n")
            return
        f.write(f"define {symbol} = [\n")
        last_idx = len(cidrs) - 1
        for idx, cidr in enumerate(cidrs):
            suffix = "" if idx == last_idx else ","
            f.write(f"  {cidr}+{suffix}\n")
        f.write("];\n")


def write_routeros_address_list(
    filepath: str,
    list_name: str,
    cidrs: list[str],
    timestamp: Optional[str] = None,
    ip_version: int = 4,
) -> None:
    ts = _resolve_timestamp(timestamp)
    section = "/ipv6 firewall address-list" if ip_version == 6 else "/ip firewall address-list"
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(f"# RouterOS address-list: {list_name}\n")
        f.write(f"# Generated by dobby-routes on {ts} UTC\n")
        f.write(f"# Total routes: {len(cidrs)}\n")
        f.write(f"{section}\n")
        f.write(f'remove [find list="{list_name}"]\n')
        for cidr in cidrs:
            f.write(f'add list="{list_name}" address={cidr}\n')


def write_nftables_set(
    filepath: str,
    symbol: str,
    cidrs: list[str],
    timestamp: Optional[str] = None,
) -> None:
    ts = _resolve_timestamp(timestamp)
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(f"# nftables set definition: {symbol}\n")
        f.write(f"# Generated by dobby-routes on {ts} UTC\n")
        f.write(f"# Total routes: {len(cidrs)}\n")
        if not cidrs:
            f.write(f"define {symbol} = {{}}\n")
            return
        f.write(f"define {symbol} = {{\n")
        last_idx = len(cidrs) - 1
        for idx, cidr in enumerate(cidrs):
            suffix = "" if idx == last_idx else ","
            f.write(f"  {cidr}{suffix}\n")
        f.write("}\n")


def write_singbox_ruleset(filepath: str, cidrs: list[str]) -> None:
    payload = {
        "version": 3,
        "rules": [{"ip_cidr": cidrs}],
    }
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)
        f.write("\n")


def write_stats(filepath: str, stats: dict[str, object]) -> None:
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(stats, f, indent=2, sort_keys=True)
        f.write("\n")
