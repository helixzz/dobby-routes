import json
from datetime import datetime, timezone
from typing import Optional


def _resolve_timestamp(timestamp: Optional[str]) -> str:
    if timestamp is None:
        return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    return timestamp


def write_annotated(
    filepath: str,
    annotated_routes: list[tuple[str, str]],
    timestamp: Optional[str] = None,
    ip_version: int = 4,
) -> None:
    ts = _resolve_timestamp(timestamp)
    label = "IPv6" if ip_version == 6 else "IP"
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(f"# China mainland {label} route table (annotated)\n")
        f.write(f"# Generated by dobby-routes on {ts} UTC\n")
        f.write(f"# Total routes: {len(annotated_routes)}\n")
        f.write("#\n")
        for cidr, annotation in annotated_routes:
            f.write(f"{cidr}  # {annotation}\n")


