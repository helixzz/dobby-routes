import json
from datetime import datetime, timezone
from typing import Optional


def _resolve_timestamp(timestamp: Optional[str]) -> str:
    if timestamp is None:
        return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    return timestamp


def write_annotated(
    filepath: str,
    annotated_routes: list[tuple[str, str]],
    timestamp: Optional[str] = None,
    ip_version: int = 4,
) -> None:
    ts = _resolve_timestamp(timestamp)
    label = "IPv6" if ip_version == 6 else "IP"
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(f"# China mainland {label} route table (annotated)\n")
        f.write(f"# Generated by dobby-routes on {ts} UTC\n")
        f.write(f"# Total routes: {len(annotated_routes)}\n")
        f.write("#\n")
        for cidr, annotation in annotated_routes:
            f.write(f"{cidr}  # {annotation}\n")


def write_optimized(
    filepath: str,
    cidrs: list[str],
    timestamp: Optional[str] = None,
    ip_version: int = 4,
) -> None:
    ts = _resolve_timestamp(timestamp)
    label = "IPv6" if ip_version == 6 else "IP"
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(f"# China mainland {label} route table (optimized)\n")
        f.write(f"# Generated by dobby-routes on {ts} UTC\n")
        f.write(f"# Total routes: {len(cidrs)}\n")
        f.write("#\n")
        for cidr in cidrs:
            f.write(f"{cidr}\n")


def write_complement(
    filepath: str,
    cidrs: list[str],
    timestamp: Optional[str] = None,
    ip_version: int = 4,
) -> None:
    ts = _resolve_timestamp(timestamp)
    if ip_version == 6:
        title = "# Inverse IPv6 route table (complement of China mainland IPv6 routes)\n"
    else:
        title = "# Inverse route table (complement of China mainland routes)\n"
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(title)
        f.write(f"# Generated by dobby-routes on {ts} UTC\n")
        f.write(f"# Total routes: {len(cidrs)}\n")
        f.write("#\n")
        for cidr in cidrs:
            f.write(f"{cidr}\n")


def write_stats(filepath: str, stats: dict[str, object]) -> None:
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(stats, f, indent=2, sort_keys=True)
        f.write("\n")
